/* BEGIN_FUNCTION_HDR
************************************************************************************************
* Function Name : SecM_ReverseBit_32
* Description   : This function is used for reversing 32_bit data.
*
* Inputs        : none
*
* Outputs       : none
*
* Return        : reversed 32 bits data
*
* Limitations   :
*
************************************************************************************************
END_FUNCTION_HDR */
uint32 SecM_ReverseBit_32(uint32 data)
{
    data = ((data&0x55555555UL)<<1U)|((data&0xAAAAAAAAUL)>>1U);
    data = ((data&0x33333333UL)<<2U)|((data&0xCCCCCCCCUL)>>2U);
    data = ((data&0x0F0F0F0FUL)<<4U)|((data&0xF0F0F0F0UL)>>4U);
    data = ((data&0x00FF00FFUL)<<8U)|((data&0xFF00FF00UL)>>8U);
    data = ((data&0x0000FFFFUL)<<16U)|((data&0xFFFF0000UL)>>16U);
    return data;
}
