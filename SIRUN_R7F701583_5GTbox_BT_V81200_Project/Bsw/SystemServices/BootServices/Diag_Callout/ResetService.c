void ResetService_EcuReset(uint8 type)
{
   // delay_ms(5);/*wait for current transmission job finish*/

    if(type == RESET_HARD)
    {
        /*watch dog rest is usually used here*/
        Mcu_PerformReset();
    }
    else if(type == RESET_SOFT)
    {
        /* MCU reset */
        Mcu_PerformReset();
    }
    else
    {
        /*do nothing*/
    }
}
